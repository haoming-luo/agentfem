"""Bounded ordinary-Step throughput measurement, not commercial-code comparison.

Run from an installed environment, or explicitly set PYTHONPATH=src for a
development candidate. Thread limits and MPI launch belong to the caller.
No field files or checkpoints are generated by this measurement.
"""

import argparse
import json
import resource
import sys
from time import perf_counter

import numpy as np
from mpi4py import MPI

from agentfem import __version__, constitutive, elements, fields, mesh, models, studies


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cells", nargs=3, type=int, default=(32, 8, 8))
    parser.add_argument("--steps", type=int, default=20)
    args = parser.parse_args()
    count = int(np.prod(args.cells))
    if min(args.cells) < 1 or not 1 <= args.steps <= 1000 or count > 300_000:
        parser.error("Use positive counts, at most 300000 cells and 1..1000 steps.")
    comm = MPI.COMM_WORLD
    start = perf_counter()
    domain = mesh.cuboid((0, 0, 0), (1, 0.2, 0.2), args.cells, cell_type="hexahedron")
    model = models.create(study=studies.dynamic_solid(dimension=3), mesh=domain)
    u = model.field(fields.displacement(domain))
    model.material(constitutive.isotropic_elastic(young=100, poisson=0, density=2))
    u.value.interpolate(
        lambda x: np.vstack((1e-4 * np.cos(np.pi * x[0]), 0 * x[0], 0 * x[0]))
    )
    step = model.step(
        target=u,
        element_policy=elements.uniform_strain_hex8(
            hourglass_modulus=50, hourglass_scale=0.1
        ),
        dt="auto",
        steps=args.steps,
        progress=False,
    )
    preparation = comm.allreduce(perf_counter() - start, op=MPI.MAX)
    result = step.solve_result()
    # This must remain publishable: timing is collective evidence, not a
    # rank-local object mixed into the scientific metadata.
    result.collective_manifest(comm)
    performance = result.performance
    wall = performance["stages"]["run_wall"]["seconds"]
    final = step.history_records[-1]
    record = {
        "scope": "ordinary_small_strain_elastic_hex8_step_no_field_io",
        "agentfem_version": __version__,
        "cells": count,
        "ranks": comm.size,
        "steps": args.steps,
        "preparation_seconds_max_rank": preparation,
        "run_seconds_max_rank": wall,
        "cell_increments_per_second": count * args.steps / wall,
        "dt": step.dt,
        "peak_rss_bytes_max_rank": comm.allreduce(
            int(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss)
            * (1 if sys.platform == "darwin" else 1024),
            op=MPI.MAX,
        ),
        "energy": final,
        "performance": performance,
        "interpretation": "Throughput only; no temporal accuracy or other-solver speedup claim.",
    }
    if comm.rank == 0:
        print(json.dumps(record, indent=2))


if __name__ == "__main__":
    main()
